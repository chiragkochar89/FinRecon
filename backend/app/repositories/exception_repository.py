class ExceptionRepository:
    """
    SQLite Persistent Exception & Triage Repository for LOCAL_DEMO mode.
    Maintains operational triage state across app restarts while preserving read-only financial data.
    """
    def __init__(self):
        init_db()
        self._ensure_seeded()

    def sync_reconciliation_exceptions(self, batch_id: str, exceptions: List[ExceptionModel]):
        """
        Synchronizes source-faithful exceptions generated by ReconciliationEngine with SQLite operational persistence.
        Updates financial source fields (amounts, statuses, reason descriptions, severity) while STRICTLY PRESERVING
        existing operational triage fields (assigned_to, triage_status, notes, resolution details, created_at, updated_at).
        Ensures atomic transaction commit on success and rollback on failure with reliable connection closure.
        """
        conn = get_db_connection()
        try:
            cursor = conn.cursor()

            for exc in exceptions:
                cursor.execute("SELECT exception_id FROM exceptions WHERE batch_id = ? AND transaction_id = ?", (exc.batch_id, exc.transaction_id))
                row = cursor.fetchone()
                if row:
                    existing_id = row["exception_id"]
                    # Update ONLY financial source fields, preserve operational triage fields
                    cursor.execute("""
                        UPDATE exceptions
                        SET bank_amount = ?, merchant_amount = ?, amount_difference = ?,
                            bank_status = ?, merchant_status = ?, reconciliation_status = ?,
                            severity = ?, reason_code = ?, reason_description = ?
                        WHERE exception_id = ?
                    """, (
                        exc.bank_amount, exc.merchant_amount, exc.amount_difference,
                        exc.bank_status, exc.merchant_status, exc.reconciliation_status,
                        exc.severity.value, exc.reason_code.value, exc.reason_description,
                        existing_id
                    ))
                else:
                    # Insert new exception
                    cursor.execute("""
                        INSERT INTO exceptions (
                            exception_id, batch_id, transaction_id, reason_code, reason_description,
                            severity, reconciliation_status, bank_amount, merchant_amount, amount_difference,
                            bank_status, merchant_status, triage_status, assigned_to, created_at, updated_at,
                            resolved_at, resolution_code, resolution_notes
                        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """, (
                        exc.exception_id, exc.batch_id, exc.transaction_id, exc.reason_code.value,
                        exc.reason_description, exc.severity.value, exc.reconciliation_status,
                        exc.bank_amount, exc.merchant_amount, exc.amount_difference,
                        exc.bank_status, exc.merchant_status, exc.triage_status.value,
                        exc.assigned_to, exc.created_at, exc.updated_at,
                        exc.resolved_at, exc.resolution_code.value if exc.resolution_code else None, exc.resolution_notes
                    ))
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()

